import assert from "node:assert/strict";
import { registerHooks } from "node:module";
registerHooks({ resolve(specifier, context, nextResolve) {
  if (specifier.startsWith("@/lib/")) return nextResolve(new URL(`../${specifier.slice(2)}.ts`, import.meta.url).href, context);
  return nextResolve(specifier, context);
} });
const KEY = "dartspoint:chat:v1";
const legacy = { version: 1, channels: [["private:Mila", [{ id: 3, name: "Nick", text: "Tot zo!", time: "21:00" }]]], drafts: [["private:Mila", "Mijn onvoltooide bericht"]] };
const values = new Map([[KEY, JSON.stringify(legacy)]]);
const storage = { getItem: key => values.get(key) ?? null, setItem: (key, value) => values.set(key, value) };
globalThis.window = { sessionStorage: storage, localStorage: storage };
globalThis.localStorage = storage;
const chat = await import("../lib/darts-chat-state.ts");
assert.deepEqual(chat.getOpenPrivateChatTabs(), ["Mila", "Bullseye", "Joey180"]);
assert.equal(chat.resolveChatTab("room", [], true), "");
assert.equal(chat.resolveChatTab("match", [], true), "");
assert.equal(chat.resolveChatTab("room", ["Mila"], true), "private:Mila");
assert.equal(chat.resolveChatTab("room", ["Mila"], false), "room");
assert.equal(chat.nextChatTabAfterClose("Bullseye", "private:Bullseye", ["Mila", "Bullseye", "Joey180"], true), "private:Joey180");
assert.equal(chat.nextChatTabAfterClose("Joey180", "private:Joey180", ["Mila", "Joey180"], true), "private:Mila");
assert.equal(chat.nextChatTabAfterClose("Mila", "room", ["Mila"], false), "room");
assert.equal(chat.closePrivateChatTab("Mila", "private:Mila", true), "private:Bullseye");
assert.equal(chat.getChatChannel("private:Mila")[0].text, "Tot zo!");
assert.equal(chat.getChatDraft("private:Mila"), "Mijn onvoltooide bericht");
assert.equal(chat.closePrivateChatTab("Bullseye", "private:Bullseye", true), "private:Joey180");
assert.equal(chat.closePrivateChatTab("Joey180", "private:Joey180", true), "");
assert.deepEqual(chat.getOpenPrivateChatTabs(), []);
assert.equal(JSON.parse(values.get(KEY)).version, 2);
assert.deepEqual(JSON.parse(values.get(KEY)).openPrivateTabs, []);
// Incoming messages update the inbox/history without forcing a closed tab open.
assert.equal(chat.receivePrivateMessage("Mila", "Ik ben er."), true);
assert.deepEqual(chat.getOpenPrivateChatTabs(), []);
assert.equal(chat.getChatChannel("private:Mila").at(-1).text, "Ik ben er.");
const restored = await import("../lib/darts-chat-state.ts?reload=1");
assert.deepEqual(restored.getOpenPrivateChatTabs(), []);
assert.equal(restored.getChatDraft("private:Mila"), "Mijn onvoltooide bericht");
assert.equal(restored.openPrivateChatTab("Mila"), true);
assert.equal(restored.openPrivateChatTab("Mila"), true);
assert.deepEqual(restored.getOpenPrivateChatTabs(), ["Mila"]);
assert.equal(restored.getChatChannel("private:Mila").at(-1).text, "Ik ben er.");
assert.equal(restored.getChatDraft("private:Mila"), "Mijn onvoltooide bericht");
assert.equal(restored.closePrivateChatTab("Mila", "private:Mila", false), "match");
assert.equal(restored.openPrivateChatTab("Nick"), false);
assert.equal(restored.openPrivateChatTab(" "), false);
assert.equal(restored.openPrivateChatTab(" Mila "), false);
assert.deepEqual(restored.getOpenPrivateChatTabs(), []);
assert.deepEqual(restored.getChatChannel(""), []);
restored.updateChatDraft("", "This must not become a room draft");
assert.equal(restored.getChatDraft(""), "");
console.log("Chat tab checks passed: legacy migration, adjacent fallback, private-only lobby, retained messages/drafts, closed-tab persistence, explicit reopening, and incoming messages without tab resurrection.");
