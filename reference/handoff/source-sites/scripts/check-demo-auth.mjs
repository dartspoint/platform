import assert from "node:assert/strict";
import { registerHooks } from "node:module";
registerHooks({ resolve(specifier, context, nextResolve) {
  if (specifier.startsWith("@/lib/")) return nextResolve(new URL(`../${specifier.slice(2)}.ts`, import.meta.url).href, context);
  return nextResolve(specifier, context);
} });
const auth = await import("../lib/darts-demo-auth.ts");
const session = await import("../lib/darts-session.ts");
const { demoLoginDestination } = await import("../lib/darts-login-destination.ts");
const at = 1_800_000;
const original = auth.makeDemoOtpChallenge(at, "012345");
assert.equal(auth.normalizeDemoEmail("  Player@Example.nl "), "player@example.nl");
assert.equal(auth.isValidDemoEmail("player@example.nl"), true);
for (const email of ["name", "two@@example.nl", "name @example.nl", "name@example", "a".repeat(255)+"@example.nl"]) assert.equal(auth.isValidDemoEmail(email), false);
assert.equal(auth.sanitizeOtpInput("012 345"), "012345");
assert.equal(auth.sanitizeOtpInput("01-23-45"), "012345");
assert.equal(auth.verifyDemoOtp(original, "012345", at + 1).status, "verified");
assert.equal(auth.verifyDemoOtp(original, "01234", at + 1).status, "invalid-format");
assert.equal(auth.verifyDemoOtp(original, "012345", at + auth.DEMO_OTP_TTL_MS).status, "expired");
let challenge = original;
for (let attempt=1; attempt<=5; attempt++) {
  const result = auth.verifyDemoOtp(challenge, "999999", at + 1);
  assert.equal(result.challenge.attempts, attempt);
  assert.equal(result.status, attempt < 5 ? "incorrect" : "locked");
  challenge = result.challenge;
}
assert.equal(auth.verifyDemoOtp(challenge, "012345", at + 2).status, "locked");
const replacement = auth.makeDemoOtpChallenge(at + 60000, "123456");
assert.equal(auth.verifyDemoOtp(replacement, original.code, at + 60001).status, "incorrect");
assert.equal(auth.demoOtpSendWait([], at), 0);
assert.equal(auth.demoOtpSendWait([at], at + 1000), 59000);
assert.equal(auth.demoOtpSendWait([at], at + 60000), 0);
const sends = [at, at+60000, at+120000, at+180000, at+240000];
assert.equal(auth.demoOtpSendWait(sends, at+300000), 600000);
assert.equal(auth.demoOtpSendWait(sends, at+900000), 0);
for (const name of ["Admin", "OWNER", "Beheerder", "security", "Nick", "nIcK", "Bullseye", "DartsPointTeam", "a", "AB", "a".repeat(21), "with space", "<script>", "Élodie"]) assert.ok(auth.usernameProblem(name, []));
for (const name of ["NewPlayer", "User_180", "Triple-7", "012", "a".repeat(20)]) assert.equal(auth.usernameProblem(name, []), null);
const fingerprint = await auth.demoEmailFingerprint(" Player@Example.nl ");
assert.match(fingerprint, /^[a-f0-9]{64}$/);
assert.equal(fingerprint, await auth.demoEmailFingerprint("player@example.nl"));
const secondFingerprint = await auth.demoEmailFingerprint("other@example.nl");
assert.notEqual(fingerprint, secondFingerprint);
const values = new Map();
const storage = { getItem: key => values.get(key) ?? null, setItem: (key, value) => values.set(key, value), removeItem: key => values.delete(key) };
globalThis.window = { localStorage: storage, sessionStorage: storage };
const profile = { emailFingerprint: fingerprint, username: "NewPlayer", role: "player", rating: 1500, createdAt: at };
assert.equal(auth.saveDemoAuthProfile(profile), true);
assert.deepEqual(auth.readDemoAuthProfiles(), [profile]);
assert.equal(auth.readDemoAuthProfiles().find(saved => saved.emailFingerprint === fingerprint)?.username, "NewPlayer");
assert.ok(auth.usernameProblem("newPLAYER", auth.readDemoAuthProfiles(), secondFingerprint));
assert.equal(auth.usernameProblem("NewPlayer", auth.readDemoAuthProfiles(), fingerprint), null);
assert.equal(values.get(auth.DEMO_AUTH_PROFILES_KEY).includes("player@example.nl"), false);
assert.equal(values.get(auth.DEMO_AUTH_PROFILES_KEY).includes("012345"), false);
session.startDemoSession(profile);
assert.equal(session.readDemoSession(), true);
assert.deepEqual(session.readDemoSessionProfile(), { username: "NewPlayer", role: "player", rating: 1500 });
session.endDemoSession();
assert.equal(session.readDemoSession(), false);
assert.equal(session.readDemoSessionProfile(), null);
assert.equal(auth.readDemoAuthProfiles()[0].username, "NewPlayer");
values.set(auth.DEMO_AUTH_PROFILES_KEY, JSON.stringify([{...profile, role:"owner"}]));
assert.deepEqual(auth.readDemoAuthProfiles(), []);
for (const route of ["/lobby", "/spelen", "/divisies", "/clubhuis", "/oefenen", "/toernooi/cup-afterhours-open"]) assert.equal(demoLoginDestination(`?next=${encodeURIComponent(route)}`), route);
for (const route of ["https://evil.example", "//evil.example", "/beheer", "/toernooi/../../beheer", "/spelen?role=owner", "javascript:alert(1)"]) assert.equal(demoLoginDestination(`?next=${encodeURIComponent(route)}`), "/lobby");
console.log("Demo OTP checks passed: input/paste, email normalization, expiry, attempts, resend invalidation/cooldown/limit, reserved and unique usernames, returning profile, no raw email/code persistence, player-only session, and safe destination.");
