import assert from "node:assert/strict";
import { registerHooks } from "node:module";
registerHooks({ resolve(specifier, context, nextResolve) {
  if (specifier.startsWith("@/lib/")) return nextResolve(new URL(`../${specifier.slice(2)}.ts`, import.meta.url).href, context);
  return nextResolve(specifier, context);
} });
const values = new Map();
const storage = { getItem: key => values.get(key) ?? null, setItem: (key, value) => values.set(key, value) };
globalThis.localStorage = storage;
globalThis.window = { localStorage: storage };
const ops = await import("../lib/darts-admin-operations.ts");
assert.equal(ops.getAdminOperations().members.length, 11);
assert.equal(ops.getAdminOperations().rooms.length, 6);
assert.equal(ops.updateAdminMemberRole("Nick", "player").ok, false);
assert.equal(ops.updateAdminMemberRole("Rookie", "owner").ok, false);
assert.equal(ops.applyAdminMemberAction({ name: "Nick", kind: "suspend", minutes: 60, reason: "Owner protection" }).ok, false);
assert.equal(ops.applyAdminMemberAction({ name: "Rookie", kind: "mute", minutes: 0, reason: "Invalid duration" }).ok, false);
assert.equal(ops.applyAdminMemberAction({ name: "Rookie", kind: "mute", minutes: 60, reason: " " }).ok, false);
assert.equal(ops.applyAdminMemberAction({ name: "Rookie", kind: "mute", minutes: 60, reason: "Wrong subject", caseId: "DEMO-001" }).ok, false);
assert.equal(ops.updateAdminMemberRole("Mila", "player").ok, true);
assert.equal(ops.getAdminOperations().rooms.some(room => room.moderator === "Mila"), false);
assert.equal(ops.updateAdminMemberRole("Mila", "admin").ok, true);
const mute = ops.applyAdminMemberAction({ name: "Rookie", kind: "mute", minutes: 60, reason: "Repeated chat spam" });
assert.equal(mute.ok, true);
const rookie = ops.getAdminOperations().members.find(member => member.name === "Rookie");
assert.equal(ops.memberStatus(rookie), "muted");
assert.equal(ops.memberStatus(rookie, rookie.sanctions[0].until + 1), "active");
assert.equal(ops.revokeAdminMemberAction("Rookie", mute.id, "Reviewed context").ok, true);
assert.equal(ops.memberStatus(ops.getAdminOperations().members.find(member => member.name === "Rookie")), "active");
const room = ops.getAdminOperations().rooms[0];
const { id, count, matches, ...form } = room;
assert.equal(ops.saveAdminRoom({ ...form, name: "Too large", capacity: 51 }).ok, false);
assert.equal(ops.saveAdminRoom({ ...form, name: room.name.toUpperCase() }).ok, false);
assert.equal(ops.saveAdminRoom({ ...form, id, capacity: count - 1 }).ok, false);
assert.equal(ops.saveAdminRoom({ ...form, name: "Bad range", minRating: 1600, maxRating: 1500 }).ok, false);
assert.equal(ops.closeAdminRoom(id).ok, true);
const closed = ops.getAdminOperations().rooms.find(item => item.id === id);
assert.equal(closed.count, count);
assert.equal(closed.matches, matches);
assert.equal(closed.status, "closed");
assert.equal(ops.deleteAdminRoom(id).ok, false);
const created = ops.saveAdminRoom({ ...form, name: "Test room", capacity: 8 });
assert.equal(created.ok, true);
assert.equal(ops.deleteAdminRoom(created.id).ok, false);
assert.equal(ops.closeAdminRoom(created.id).ok, true);
assert.equal(ops.deleteAdminRoom(created.id).ok, true);
assert.equal(ops.updateAdminCase("DEMO-001", "resolved", "").ok, false);
assert.equal(ops.updateAdminCase("DEMO-001", "review", "Reviewing context").ok, true);
assert.equal(ops.applyAdminMemberAction({ name: "NightOwl", kind: "warn", reason: "Stop repeated invitations", caseId: "DEMO-001" }).ok, true);
assert.equal(ops.getAdminOperations().cases.find(item => item.id === "DEMO-001").status, "resolved");
assert.equal(ops.applyAdminMemberAction({ name: "NightOwl", kind: "warn", reason: "Duplicate action prevented", caseId: "DEMO-001" }).ok, false);
const report = { id: "local-report", name: "Rookie", room: "Nederland 1", gameId: "83626", reason: "Test report", detail: "Evidence", context: "Chat", createdAt: Date.now(), status: "Nieuw" };
ops.syncAdminReports([report]);
ops.syncAdminReports([report]);
assert.equal(ops.getAdminOperations().cases.filter(item => item.id === report.id).length, 1);
assert.ok(ops.getAdminOperations().audit.length >= 10);
const restored = await import("../lib/darts-admin-operations.ts?reload=1");
assert.equal(restored.getAdminOperations().rooms.find(item => item.id === id).status, "closed");
assert.equal(restored.getAdminOperations().cases.find(item => item.id === "DEMO-001").status, "resolved");
assert.deepEqual(restored.getAdminOperations().audit, ops.getAdminOperations().audit);
restored.resetAdminOperations();
assert.equal(restored.getAdminOperations().rooms[0].status, "active");
assert.equal(restored.getAdminOperations().audit.length, 1);
console.log("Admin operations checks passed: owner protection, role handover, sanctions/expiry/revocation, case resolution/idempotency, capacity/duplicate validation, safe room closure/deletion and persisted restore.");
