import assert from "node:assert/strict";
import { registerHooks } from "node:module";
registerHooks({ resolve(specifier, context, next) { if ((specifier.startsWith("./") || specifier.startsWith("../")) && !/\.[a-z]+$/i.test(specifier)) return next(`${specifier}.ts`, context); return next(specifier, context); } });
const { initialGameState, dartsGameReducer } = await import("../lib/darts-game-state.ts");
const { scoreDart } = await import("../lib/darts-rules.ts");
let id = 0;
const treble20 = scoreDart(0, -103 / 170);
const double20 = scoreDart(0, -166 / 170);
const single20 = scoreDart(0, -.4);
function throwHit(state, hit) {
  if (state.phase === "horizontal") state = dartsGameReducer(state, { type: "lock-x" });
  const before = state;
  const dartId = ++id;
  state = dartsGameReducer(state, { type: "launch", dart: { id: dartId, hit, opponentName: "Bullseye" } });
  assert.deepEqual(state.scores, before.scores, "Airborne dart cannot affect score");
  assert.deepEqual(state.events, before.events, "Airborne dart cannot enter history");
  state = dartsGameReducer(state, { type: "land", id: dartId, at: 1000 + dartId });
  assert.equal(state.events.at(-1).id, dartId);
  assert.equal(state.events.at(-1).hit.label, hit.label);
  return state;
}
let game = initialGameState(0, "game-test", 100);
for (let i = 0; i < 3; i++) game = throwHit(game, treble20);
assert.deepEqual(game.scores, [321, 501]);
assert.equal(game.turn, 1); assert.equal(game.celebration, "180");
assert.equal(game.highestVisit[0], 180); assert.equal(game.events.length, 3);
assert.deepEqual(game.events.map(x => x.visit), [1, 1, 1]);
game = throwHit(game, single20);
assert.equal(game.events.at(-1).visit, 2); assert.equal(game.events.at(-1).player, 1);
const serialised = JSON.parse(JSON.stringify(game));
const restored = dartsGameReducer(initialGameState(), { type: "restore", state: serialised });
assert.deepEqual(restored, game, "Restore settled state including exact board hits and history");
const replay = dartsGameReducer(game, { type: "land", id });
assert.equal(replay, game, "Duplicate animation callback cannot score twice");
let bust = { ...initialGameState(), scores: [41,501], visitStart: 41 };
bust = throwHit(bust, double20);
assert.equal(bust.scores[0], 41); assert.equal(bust.events[0].bust, true);
assert.match(bust.bustReason, /1 over/); assert.equal(bust.visitScores[0], 0);
let wrongFinish = { ...initialGameState(), scores: [20,501], visitStart: 20 };
wrongFinish = throwHit(wrongFinish, single20); assert.equal(wrongFinish.scores[0],20); assert.match(wrongFinish.bustReason,/zonder dubbel/);
let finish = { ...initialGameState(1), turn: 0, phase: "horizontal", scores: [40,501], visitStart: 40 };
finish = throwHit(finish, double20);
assert.equal(finish.legs[0], 1); assert.equal(finish.highestCheckout[0],40); assert.equal(finish.celebration,"checkout");
assert.equal(finish.turn,0,"When opponent started leg 1, Nick starts leg 2");
finish = { ...finish, scores: [40,501], visitStart:40 };
finish = throwHit(finish,double20); assert.equal(finish.winner,0); assert.equal(finish.phase,"won");
const again = dartsGameReducer(finish,{type:"reset",starter:0,id:"rematch",at:200}); assert.equal(again.starter,0); assert.equal(again.events.length,0); assert.equal(again.id,"rematch");
let cancel = dartsGameReducer(initialGameState(),{type:"lock-x"});
cancel = dartsGameReducer(cancel,{type:"launch",dart:{id:++id,hit:treble20,opponentName:"Bullseye"}});
cancel = dartsGameReducer(cancel,{type:"reset",id:"next"});
assert.equal(dartsGameReducer(cancel,{type:"land",id}).scores[0],501,"Stale pre-reset flight cannot score");
const forfeited = dartsGameReducer(restored,{type:"forfeit",player:0}); assert.equal(forfeited.winner,1); assert.equal(forfeited.forfeit,true); assert.equal(forfeited.pendingDart,null);
console.log("Game checks passed: impact-only scoring/history, 180, per-visit grouping, exact restore, duplicate/stale landing protection, bust explanations, checkout, alternating starters and forfeit.");
